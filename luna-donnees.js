/* Les encarts : la vente en sept étapes, un carré par usage. */
(function () {
    'use strict';
    var F = { 'Code': '--f-code', 'Conversation': '--f-conversation', 'Compétence': '--f-competence', 'Écran': '--f-ecran', 'Agent': '--f-agent' };
    var E = ['Connaître son marché', 'Prospecter', 'Qualifier', 'Proposer', 'Négocier', 'Conclure', 'Suivre et fidéliser'];
    var C = ['Marché', 'Prospecter', 'Qualifier', 'Proposer', 'Négocier', 'Conclure', 'Suivre'];
    document.querySelectorAll('[data-luna-mini]').forEach(function (m) {
        var lab = m.hasAttribute('data-etiquettes');
        m.innerHTML = E.map(function (e, i) {
            var u = window.LUNA.usages.filter(function (x) { return x.etape === e; });
            return '<div>' + (lab ? '<small>' + C[i] + '</small>' : '') + u.map(function (x) {
                return '<i class="' + (x.etat === "À l'étude" ? 'etude' : '') + '" style="--c: var(' + F[x.mieux] + ')"></i>';
            }).join('') + '</div>';
        }).join('');
    });
})();
